"""Contract every language pack must satisfy. Phrase keys must match the keys
the (language-agnostic) state machine requests; it knows keys, never text."""

from __future__ import annotations

from typing import Protocol, runtime_checkable


@runtime_checkable
class LanguagePack(Protocol):
    name: str
    voice_id: str | None
    model_id: str | None
    phrases: dict[str, str]

    def build_declaration(self, processed: dict) -> str: ...
    def name_with_title(self, processed: dict) -> str: ...
    def time_based_greeting(self) -> str: ...
    def format_phone(self, phone: str) -> str: ...
    def format_email(self, email: str) -> str: ...
    def format_address(self, addr: str) -> str: ...
    def number_to_words(self, n: int) -> str: ...
    def ensure_number_words(self, value: str) -> str: ...
    def format_date(self, date_str: str) -> str: ...
